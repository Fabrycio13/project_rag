-- Private PDF storage only; no processing. Apply manually after organization_agents.
begin;
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('agent-documents', 'agent-documents', false, 10485760, array['application/pdf']);
create table public.agent_documents (
 id uuid primary key default gen_random_uuid(),
 organization_id uuid not null references public.organizations(id) on delete restrict,
 agent_id uuid not null references public.agents(id) on delete restrict,
 filename text not null check (char_length(filename) between 5 and 180 and filename ~* '\.pdf$' and filename !~ '[[:cntrl:]/\\]'),
 size_bytes bigint not null check (size_bytes between 8 and 10485760),
 storage_path text generated always as (organization_id::text || '/' || agent_id::text || '/' || id::text || '.pdf') stored unique,
 upload_state text not null default 'pending' check (upload_state in ('pending','stored','failed')),
 created_at timestamptz not null default now()
);
create index agent_documents_agent_created on public.agent_documents(agent_id, created_at desc);
alter table public.agent_documents enable row level security;
revoke all on public.agent_documents from public, anon, authenticated;
grant select on public.agent_documents to authenticated;
grant insert (id, organization_id, agent_id, filename, size_bytes) on public.agent_documents to authenticated;
grant update (upload_state) on public.agent_documents to authenticated;
-- Invoker function: existing RLS remains in force, Clerk sub is text (not auth.uid()).
create function public.can_access_agent_documents(org uuid, agent uuid) returns boolean
language sql stable security invoker set search_path = '' as $$
 select exists (select 1 from public.organizations o join public.agents a on a.organization_id=o.id
 where o.id=org and a.id=agent and o.archived_at is null and o.owner_clerk_user_id=(select auth.jwt()->>'sub'))
 and exists (select 1 from public.platform_users p where p.clerk_user_id=(select auth.jwt()->>'sub') and p.role in ('owner','admin') and p.status='active');
$$;
revoke all on function public.can_access_agent_documents(uuid,uuid) from public;
grant execute on function public.can_access_agent_documents(uuid,uuid) to authenticated;
create policy documents_select on public.agent_documents for select to authenticated using (public.can_access_agent_documents(organization_id,agent_id));
create policy documents_insert on public.agent_documents for insert to authenticated with check (upload_state='pending' and public.can_access_agent_documents(organization_id,agent_id));
create policy documents_update on public.agent_documents for update to authenticated using (upload_state='pending' and public.can_access_agent_documents(organization_id,agent_id)) with check (public.can_access_agent_documents(organization_id,agent_id));
-- Metadata is immutable via column grants. Only pending uploads may create objects.
-- Validate terminal state against Storage metadata at the database boundary.
create function public.check_document_storage_state() returns trigger
language plpgsql security invoker set search_path = '' as $$
begin
 if old.upload_state <> 'pending' or new.upload_state not in ('stored','failed') then
  raise exception 'Invalid upload transition';
 end if;
 if new.upload_state = 'stored' and not exists (
  select 1 from storage.objects o where o.bucket_id='agent-documents' and o.name=new.storage_path
   and (o.metadata->>'size')::bigint = new.size_bytes
   and o.metadata->>'mimetype' = 'application/pdf'
 ) then raise exception 'Stored object missing or metadata mismatch'; end if;
 return new;
end;
$$;
revoke all on function public.check_document_storage_state() from public;
create trigger document_storage_state before update on public.agent_documents
for each row execute function public.check_document_storage_state();
create policy agent_document_object_insert on storage.objects for insert to authenticated with check (
 bucket_id='agent-documents' and exists (select 1 from public.agent_documents d where d.storage_path=name and d.upload_state='pending' and public.can_access_agent_documents(d.organization_id,d.agent_id))
);
-- SELECT is required by Storage remove; no public or signed URL is generated by the app.
create policy agent_document_object_select on storage.objects for select to authenticated using (
 bucket_id='agent-documents' and exists (select 1 from public.agent_documents d where d.storage_path=name and public.can_access_agent_documents(d.organization_id,d.agent_id))
);
create policy agent_document_object_compensate on storage.objects for delete to authenticated using (
 bucket_id='agent-documents' and exists (select 1 from public.agent_documents d where d.storage_path=name and d.upload_state in ('pending','failed') and public.can_access_agent_documents(d.organization_id,d.agent_id))
);
commit;
